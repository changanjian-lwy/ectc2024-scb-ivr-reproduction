"""Digitize the GS61008T datasheet's own Coss-vs-Vds curve.

EXTERNAL_DEVICE_DATA. Source (see A47 BOUNDARY.md for the full provenance
statement):

  GS61008T datasheet, Rev 200402, (c) 2009-2020 GaN Systems Inc.
  Page 8 of the PDF ("page index 7" 0-based with PyMuPDF), Figure 7:
  "Typical CISS, COSS, CRSS vs. VDS".
  Retrieved via the Infineon-hosted republication of the same GaN Systems
  document:
    https://www.infineon.com/dgdl/Infineon-GS61008T-DataSheet-v01_00-EN.pdf?fileId=8ac78c8c8d2fe47b018e5160eb52522a
  (This is the same Rev 200402 document already used elsewhere in this
  project for GS61008T_typical_params.lib / GS61008T_commutation_capacitance.lib
  -- confirmed by the "Rev 200402" text printed on every page and by the
  in-document Electrical Characteristics table matching the values already
  recorded in GS61008T_typical_params.lib: RDS(on)=7 mOhm typ, COSS=250 pF,
  CO(ER)=302 pF, CO(TR)=385 pF, all at TJ=25C.)

Method: the PDF page is rendered to a 400-DPI raster (this is a vector-drawn
figure in the source PDF re-rasterized at high resolution, not a low-quality
scan), the "Capacitance Characteristics" quadrant is cropped, and pixel
positions are calibrated against the plot's own printed axis tick labels and
gridlines (never against assumed round-number pixel positions). The COSS
trace (the middle of the three CISS/COSS/CRSS curves) is then traced
column-by-column with a right-to-left nearest-neighbour continuity tracker,
seeded at V=100V where COSS is unambiguously separated from the other two
curves.

Calibration is cross-checked against three values PRINTED ELSEWHERE in the
same datasheet (not read off the plot): COSS=250pF (typ, implicitly at
Vds=50V, sharing the row above's stated condition), CO(ER)=302pF (the
0-50V energy-equivalent capacitance) and CO(TR)=385pF (the 0-50V
time-equivalent capacitance already used as GS61008T_COTR_0_50V elsewhere in
this project). See BOUNDARY.md for the resulting cross-check numbers and
their honestly-stated residual error (regenerated by running this script).

Usage:
    python3 digitize_gs61008t_coss.py /path/to/GS61008T_datasheet.pdf

The datasheet PDF itself is external device data and is NOT committed to
this repository (paper/datasheet PDFs are excluded from the archive per
EXPERIMENT_PROTOCOL_AND_ARCHIVE_RULES.md Section XII). The output of this
script -- gs61008t_coss_digitized_raw.csv -- IS committed, and is what
fit_nonlinear_coss.py actually reads; this script is committed for
methodology transparency and is re-runnable by anyone who fetches the same
datasheet revision from the URL above.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

try:
    import fitz  # PyMuPDF
except ImportError as exc:  # pragma: no cover
    raise SystemExit("PyMuPDF (pip install pymupdf) is required") from exc


HERE = Path(__file__).resolve().parent
OUT_CSV = HERE / "gs61008t_coss_digitized_raw.csv"

# Figure 7 is on the page with 0-based index 7 (printed page 8) of the
# Rev 200402 datasheet PDF, in the bottom-left quadrant of the
# "Electrical Performance Graphs" page.
PAGE_INDEX = 7
RENDER_DPI = 400

# Bottom-left quadrant crop box, in pixels of the 400-DPI page render
# (3400x4400 px for a 612x792-pt page). Chosen by visual inspection of the
# rendered page to generously bound the "Capacitance Characteristics"
# quadrant (title, axes box and caption); the axis calibration below does
# NOT depend on this box being pixel-exact, only on it fully containing the
# plot box and its tick labels.
QUAD_BOX = (396, 2244, 1672, 3872)  # (left, top, right, bottom)


def render_quadrant(pdf_path: Path) -> np.ndarray:
    doc = fitz.open(str(pdf_path))
    page = doc[PAGE_INDEX]
    pix = page.get_pixmap(dpi=RENDER_DPI)
    full = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, pix.n)
    gray = full[..., :3].mean(axis=2).astype(np.float64)
    l, t, r, b = QUAD_BOX
    return gray[t:b, l:r]


def find_full_width_lines(arr: np.ndarray, thresh: float = 220.0, frac: float = 0.6) -> list[int]:
    """Row indices where a near-full-width dark horizontal line is drawn."""
    dark = arr < thresh
    row_sums = dark.sum(axis=1)
    width = arr.shape[1]
    rows = np.flatnonzero(row_sums > frac * width)
    # collapse consecutive rows into single representative centers
    groups: list[list[int]] = []
    for r in rows:
        if groups and r - groups[-1][-1] <= 2:
            groups[-1].append(r)
        else:
            groups.append([r])
    return [int(np.mean(g)) for g in groups]


def find_full_height_lines(arr: np.ndarray, thresh: float = 220.0, frac: float = 0.6) -> list[int]:
    dark = arr < thresh
    col_sums = dark.sum(axis=0)
    height = arr.shape[0]
    cols = np.flatnonzero(col_sums > frac * height)
    groups: list[list[int]] = []
    for c in cols:
        if groups and c - groups[-1][-1] <= 2:
            groups[-1].append(c)
        else:
            groups.append([c])
    return [int(np.mean(g)) for g in groups]


def calibrate(arr: np.ndarray) -> dict:
    """Recover the (row<->pF, col<->Vds) calibration from the plot's own
    gridlines. The y-axis is log-scale (decades at 1000/100/10/1 pF), the
    x-axis is linear 0-100 V.
    """
    v_lines = find_full_height_lines(arr)
    # Expect 7 near-full-height vertical lines: outer-frame L, V=0..100 (6
    # gridlines every 20V), outer-frame R. Keep the middle 6 (the axis box
    # border + 5 interior + border == 7 total; V gridlines are all but the
    # two outermost).
    if len(v_lines) < 7:
        raise RuntimeError(f"expected >=7 vertical reference lines, found {v_lines}")
    v_grid_cols = v_lines[1:7]  # V=0,20,40,60,80,100
    col_v0, col_v100 = v_grid_cols[0], v_grid_cols[-1]
    px_per_volt = (col_v100 - col_v0) / 100.0

    # Major horizontal gridlines for C=1000,100,10,1 are found by searching
    # narrow row windows around the decade positions implied by the
    # y-axis tick LABEL text centers (found separately, see
    # `label_row_centers`), then confirmed as an actual full-width line.
    label_rows = label_row_centers(arr)
    decade_rows = []
    for approx in label_rows:
        lo, hi = int(approx - 25), int(approx + 25)
        cand = [r for r in find_full_width_lines(arr[lo:hi, :]) ]
        if not cand:
            raise RuntimeError(f"no gridline found near label row {approx}")
        decade_rows.append(lo + cand[0])

    row_c1000, row_c100, row_c10, row_c1 = decade_rows
    spacings = [row_c100 - row_c1000, row_c10 - row_c100, row_c1 - row_c10]
    px_per_decade = float(np.mean(spacings))

    return {
        "col_v0": col_v0,
        "col_v100": col_v100,
        "px_per_volt": px_per_volt,
        "row_c1000": row_c1000,
        "px_per_decade": px_per_decade,
        "decade_row_spacings": spacings,
    }


def label_row_centers(arr: np.ndarray) -> list[int]:
    """Locate the vertical centers of the '1,000' / '100' / '10' / '1'
    y-axis tick-label text blocks in the left margin, via connected
    components on the thresholded left-margin sub-image.
    """
    from scipy import ndimage

    margin = arr[:, :300] < 150
    lbl, _ = ndimage.label(margin)
    boxes = ndimage.find_objects(lbl)
    # Numeral glyphs in this font/size are ~30-45 px tall; keep those,
    # excluding the rotated "Capacitance (pF)" title (narrow column band)
    # and the "Figure 7: ..." caption (below the plot, row > 1300 in this
    # crop's local coordinates).
    candidates = []
    for sl in boxes:
        r0, r1 = sl[0].start, sl[0].stop
        c0, c1 = sl[1].start, sl[1].stop
        h = r1 - r0
        if 25 <= h <= 50 and (c1 - c0) >= 8 and r1 < 1330:
            candidates.append(((r0 + r1) / 2, c0, c1))
    # Group by row proximity (each numeral's digits form several boxes at
    # the same row-center); take the row center per group.
    candidates.sort()
    groups: list[list[float]] = []
    for row_c, c0, c1 in candidates:
        if groups and abs(row_c - groups[-1][-1]) < 40:
            groups[-1].append(row_c)
        else:
            groups.append([row_c])
    centers = [float(np.mean(g)) for g in groups]
    centers.sort()
    if len(centers) < 4:
        raise RuntimeError(f"expected 4 y-axis label rows, found {centers}")
    # The 4 major labels are the widest-separated / first four found top to
    # bottom (1,000 / 100 / 10 / 1); other stray text blocks may also match
    # the size filter, so pick 4 whose consecutive spacing is most uniform.
    return centers[:4] if len(centers) == 4 else _pick_uniform_four(centers)


def _pick_uniform_four(centers: list[float]) -> list[float]:
    best = None
    n = len(centers)
    for i in range(n):
        for j in range(i + 1, n):
            for k in range(j + 1, n):
                for m in range(k + 1, n):
                    quad = [centers[i], centers[j], centers[k], centers[m]]
                    d = np.diff(quad)
                    score = np.std(d)
                    if best is None or score < best[0]:
                        best = (score, quad)
    assert best is not None
    return best[1]


def row_to_pF(row: float, cal: dict) -> float:
    return 1000.0 * 10 ** (-(row - cal["row_c1000"]) / cal["px_per_decade"])


def col_to_V(col: float, cal: dict) -> float:
    return (col - cal["col_v0"]) / cal["px_per_volt"]


def clusters_in_col(arr: np.ndarray, col: int, rlo: int, rhi: int, thresh: float = 150.0):
    colpix = arr[rlo:rhi, col]
    dark = colpix < thresh
    idx = np.flatnonzero(dark)
    if len(idx) == 0:
        return []
    groups = []
    start = idx[0]
    prev = idx[0]
    for i in idx[1:]:
        if i - prev > 2:
            groups.append((start, prev))
            start = i
        prev = i
    groups.append((start, prev))
    return [(rlo + g0, rlo + g1, (rlo + g0 + rlo + g1) / 2) for g0, g1 in groups]


def trace_coss(arr: np.ndarray, cal: dict) -> list[tuple[float, float]]:
    """Trace the COSS curve right-to-left with nearest-neighbour continuity,
    seeded at the rightmost column where it sits clearly between the flat
    CISS trace (top) and the CRSS trace (bottom).
    """
    col_v0, col_v100 = cal["col_v0"], cal["col_v100"]
    search_lo, search_hi = 260, 950  # row window generously bounding CISS..CRSS
    cols = list(range(col_v100 - 3, col_v0, -1))
    seed = None
    points = []
    for c in cols:
        cl = clusters_in_col(arr, c, search_lo, search_hi)
        if not cl:
            continue
        if seed is None:
            candidates = [g for g in cl if 380 <= g[2] <= 560]
            if not candidates:
                continue
            seed = candidates[0][2]
        else:
            best = min(cl, key=lambda g: abs(g[2] - seed))
            if abs(best[2] - seed) > 60:
                continue
            seed = best[2]
        points.append((col_to_V(c, cal), row_to_pF(seed, cal)))
    points.sort()
    return points


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(f"usage: {sys.argv[0]} <path to GS61008T datasheet PDF>")
    pdf_path = Path(sys.argv[1])
    arr = render_quadrant(pdf_path)
    cal = calibrate(arr)
    print("Calibration:", cal)

    points = trace_coss(arr, cal)
    print(f"traced {len(points)} (V, Coss) points")

    # Cross-check against printed reference values (never against the plot
    # itself): COSS(50V) approx 250 pF; CO(TR) and CO(ER) integrated 0-50V.
    V = np.array([p[0] for p in points])
    C = np.array([p[1] for p in points])
    near50 = np.argmin(np.abs(V - 50))
    print(f"digitized COSS(~50V) = {C[near50]:.1f} pF  (datasheet typ: 250 pF)")

    mask = V <= 50.0
    Vc, Cc = V[mask], C[mask]
    Q50 = np.trapezoid(Cc, Vc)
    E50 = np.trapezoid(Cc * Vc, Vc)
    print(f"implied CO(TR) (0-50V) = {Q50/50.0:.1f} pF  (datasheet: 385 pF)")
    print(f"implied CO(ER) (0-50V) = {2*E50/2500.0:.1f} pF  (datasheet: 302 pF)")

    with OUT_CSV.open("w") as f:
        f.write("Vds_V,Coss_pF\n")
        for v, c in points:
            f.write(f"{v:.6f},{c:.4f}\n")
    print("wrote", OUT_CSV)


if __name__ == "__main__":
    main()
